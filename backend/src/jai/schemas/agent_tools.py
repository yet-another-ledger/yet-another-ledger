class ReceiptSubmissionSnapshot(BaseModel):
    """Allowlisted receipt result fields retained for authorized replay.

    The operation ID, created/replayed status, and target ID are generated by
    the shared transaction wrapper. This model contains the complete stable
    receipt-specific part of ``submit_receipt`` and cannot carry file payloads
    or provider response objects.
    """

    model_config = ConfigDict(extra="forbid")

    inbox_id: uuid.UUID
    ai_state: Literal["NOT_RUN", "RUNNING", "READY", "UNAVAILABLE", "FAILED"]
    ai_error_code: ReceiptAIErrorCode | None = None
    review_url: str


